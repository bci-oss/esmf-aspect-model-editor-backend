package org.eclipse.esmf.ame.ai.model.chat;

import org.eclipse.esmf.ame.ai.model.provider.AiProviderConfig;

import com.fasterxml.jackson.annotation.JsonInclude;
import io.micronaut.serde.annotation.Serdeable;
import io.micronaut.core.annotation.Nullable;

/**
 * A chat message of the user.
 *
 * @param conversationId the conversation to continue; a new one is created if missing
 * @param requestId the id generated by the client, used to cancel the request
 * @param provider the AI provider
 * @param message the text of the user
 * @param command the command, e.g. {@code explain}
 * @param context what the user sees in the editor
 */
@Serdeable
@JsonInclude( JsonInclude.Include.NON_NULL )
public record AiChatRequest(
      @Nullable String conversationId,
      String requestId,
      AiProviderConfig provider,
      @Nullable String message,
      @Nullable String command,
      @Nullable AiChatContext context
) {
   /**
    * @return the context, or an empty one if none was sent
    */
   public AiChatContext contextOrEmpty() {
      return context == null ? AiChatContext.EMPTY : context;
   }
}
